    public void preencheTabela(){
        ProcedimentoDAO pDAO = new ProcedimentoDAO();
        
        List<Procedimento> listaProcedimentos = pDAO.getProcedimentos();
        
        DefaultTableModel tabelaProcedimentos = (DefaultTableModel) tblProcedimentos.getModel();
        
        for(Procedimento p: listaProcedimentos){
            Object[] obj = new Object[]{
                p.getId(),
                p.getNome(),
                p.getDescricao(),
                p.getValor()
            };
                tabelaProcedimentos.addRow(obj);
            
            }
        }

