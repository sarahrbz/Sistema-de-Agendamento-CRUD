    private void limparformulario(){
        txtID.setText("");
        txtIDAgend.setText("");
        txtData.setText("");
        txtHorario.setText("");
        txtProfissional.setText("");
        txtCliente.setText("");
        txtTelefone.setText("");
        txtProcedimento.setText("");
        txtValor.setText("");
    }
    
    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        // TODO add your handling code here:
      Agendamento a = new Agendamento();
      a.setId(Integer.parseInt(txtIDAgend.getText()));
      a.setData(txtData.getText());
      a.setHorario(txtHorario.getText());
      a.setProfissional(txtProfissional.getText());
      a.setNomeCliente(txtCliente.getText());
      a.setTelefoneCliente(txtTelefone.getText());
      a.setProcedimento(txtProcedimento.getText());
      a.setValor(Double.parseDouble(txtValor.getText()));
      
      AgendamentoDAO aDAO = new AgendamentoDAO();
      aDAO.editar(a);
      limparformulario();
    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        int resposta = JOptionPane.showConfirmDialog(null, "Deseja realmente excluir ?",
                "Exclusão", JOptionPane.YES_NO_OPTION);
        if(resposta == JOptionPane.YES_OPTION){
            AgendamentoDAO aDAO = new AgendamentoDAO();
            aDAO.excluir(Integer.parseInt(txtIDAgend.getText()));
            limparformulario();
        }
        
    }//GEN-LAST:event_btnExcluirActionPerformed

