    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
        int idAgendamento = Integer.parseInt(txtIDAgend.getText());
        AgendamentoDAO aDAO = new AgendamentoDAO();
        
        Agendamento a = aDAO.getAgendamento(idAgendamento);
        if(a == null){
            txtID.setText("");
            txtData.setText("");
            txtHorario.setText("");
            txtProfissional.setText("");
            txtCliente.setText("");
            txtTelefone.setText("");
            txtProcedimento.setText("");
            txtValor.setText("");
            JOptionPane.showMessageDialog(this, "Pessoa não encontrada!");
        } else{
            txtID.setText(String.valueOf(a.getId()));
            txtData.setText(a.getData());
            txtHorario.setText(a.getHorario());
            txtProfissional.setText(a.getProfissional());
            txtCliente.setText(a.getNomeCliente());
            txtTelefone.setText(a.getTelefoneCliente());
            txtProcedimento.setText(a.getProcedimento());
            txtValor.setText(String.valueOf(a.getValor()));
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

