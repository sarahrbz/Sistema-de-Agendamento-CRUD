    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
        
        int idProfissional = Integer.parseInt(txtID.getText());
        ProfissionalDAO pDAO = new ProfissionalDAO();
        
        Profissional p = pDAO.getProfissional(idProfissional);
        if(p == null){
            txtID.setText("");
            txtNome.setText("");
            txtEspec.setText("");
            txtTelefone.setText("");
            JOptionPane.showMessageDialog(this, "Profissional não encontrado!");
        } else{
            txtID.setText(String.valueOf(p.getId()));
            txtNome.setText(p.getNome());
            txtEspec.setText(p.getEspecialidade());
            txtTelefone.setText(p.getTelefone());
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

    public void limparformulario(){
        txtID.setText("");
        txtNome.setText("");
        txtEspec.setText("");
        txtTelefone.setText("");
    }
    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        int resposta = JOptionPane.showConfirmDialog(null, "Deseja realmente excluir ?",
                "Exclusão", JOptionPane.YES_NO_OPTION);
        if(resposta == JOptionPane.YES_OPTION){
            ProfissionalDAO pDAO = new ProfissionalDAO();
            pDAO.excluir(Integer.parseInt(txtID.getText()));
            limparformulario();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        Profissional p = new Profissional();
        p.setId(Integer.parseInt(txtID.getText()));
        p.setNome(txtNome.getText());
        p.setEspecialidade(txtEspec.getText());
        p.setTelefone(txtTelefone.getText());
        
        ProfissionalDAO pDAO = new ProfissionalDAO();
        
        pDAO.editar(p);
        limparformulario();
    }//GEN-LAST:event_btnEditarActionPerformed

