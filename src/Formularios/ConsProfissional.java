    public void preencheTabela(){
        ProfissionalDAO pDAO = new ProfissionalDAO();
        
        List<Profissional> listaProfissionais = pDAO.getProfissionais();
        
        DefaultTableModel tabelaProfissionais = (DefaultTableModel) tblProfissionais.getModel();
        
        for(Profissional p: listaProfissionais){
            Object[] obj = new Object[]{
                p.getId(),
                p.getNome(),
                p.getEspecialidade()
            };
                tabelaProfissionais.addRow(obj);
            
            }
    }

