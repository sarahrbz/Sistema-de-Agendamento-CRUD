    private void carregarProfissionais() {

    ProfissionalDAO pDAO = new ProfissionalDAO();

    List<Profissional> lista = pDAO.getProfissionais();

    cbProfissional.removeAllItems();

    if (lista != null) {
        for (Profissional p : lista) {
            cbProfissional.addItem(p);
        }
    }

    cbProfissional.setSelectedIndex(-1);
}
    
    private void carregarProcedimentos() {

    ProcedimentoDAO pDAO = new ProcedimentoDAO();

    List<Procedimento> lista = pDAO.getProcedimentos();

    cbProcedimento.removeAllItems();

    if (lista != null) {
        for (Procedimento p : lista) {
            cbProcedimento.addItem(p);
        }
    }

    cbProcedimento.setSelectedIndex(-1);
}
    private void limparformulario(){
        txtData.setText("");
        txtHorario.setText("");
        
        txtCliente.setText("");
        txtTelefone.setText("");
        
        txtValor.setText("");
        
        
    cbProfissional.setSelectedIndex(-1);
    cbProcedimento.setSelectedIndex(-1);
    }
    private void btnAgendarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgendarActionPerformed
        // TODO add your handling code here:
        Profissional profissional =
        (Profissional) cbProfissional.getSelectedItem();

    Procedimento procedimento =
        (Procedimento) cbProcedimento.getSelectedItem();

    if (profissional == null || procedimento == null) {
        JOptionPane.showMessageDialog(this,
            "Selecione um profissional e um procedimento!");
        return;
    }

    if (txtData.getText().trim().isEmpty() ||
        txtHorario.getText().trim().isEmpty() ||
        txtCliente.getText().trim().isEmpty() ||
        txtTelefone.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this,
            "Preencha todos os campos obrigatórios!");
        return;
    }

    Agendamento a = new Agendamento();

    a.setData(txtData.getText());
    a.setHorario(txtHorario.getText());

    a.setProfissional(profissional.getNome());

    a.setNomeCliente(txtCliente.getText());
    a.setTelefoneCliente(txtTelefone.getText());

    a.setProcedimento(procedimento.getNome());
    a.setValor(procedimento.getValor());

    AgendamentoDAO aDAO = new AgendamentoDAO();
    aDAO.inserir(a);

    limparformulario();
        
        
        
    }//GEN-LAST:event_btnAgendarActionPerformed

