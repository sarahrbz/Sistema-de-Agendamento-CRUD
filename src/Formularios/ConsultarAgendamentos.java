    private void carregarProfissionais() {

        ProfissionalDAO pDAO = new ProfissionalDAO();

        List<Profissional> lista = pDAO.getProfissionais();

        cbFiltroProfissional.removeAllItems();

        cbFiltroProfissional.addItem("Todos os profissionais");

        if (lista != null) {
            for (Profissional p : lista) {
            cbFiltroProfissional.addItem(p.getNome());
            }
        }

        cbFiltroProfissional.setSelectedIndex(0);
    }
    
    public void preencheTabela(List<Agendamento> listaAgendamentos) {

        DefaultTableModel tabelaAgendamentos =
            (DefaultTableModel) tblAgendamento.getModel();

        tabelaAgendamentos.setRowCount(0);

        if (listaAgendamentos == null) {
            return;
        }

        for (Agendamento a : listaAgendamentos) {

            Object[] obj = new Object[]{
                a.getId(),
                a.getData(),
                a.getHorario(),
                a.getProfissional(),
                a.getNomeCliente(),
                a.getTelefoneCliente(),
                a.getProcedimento(),
                a.getValor()
            };

            tabelaAgendamentos.addRow(obj);
        }
    }
    
    private void filtrarAgendamentos() {

        String profissional =
            (String) cbFiltroProfissional.getSelectedItem();

        if (profissional == null) {
            return;
        }

        AgendamentoDAO aDAO = new AgendamentoDAO();

        List<Agendamento> lista;

        if (profissional.equals("Todos os profissionais")) {

            lista = aDAO.getAgendamentos();

        } else {

            lista = aDAO.getAgendamentosPorProfissional(profissional);

        }

        preencheTabela(lista);
    }

