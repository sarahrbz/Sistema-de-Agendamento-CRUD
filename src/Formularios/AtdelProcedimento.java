    public void limparformulario(){
        txtID.setText("");
        txtProcedimento.setText("");
        txtDescricao.setText("");
        txtValor.setText("");
    }
    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        Procedimento p = new Procedimento();
        p.setId(Integer.parseInt(txtID.getText()));
        p.setNome(txtProcedimento.getText());
        p.setDescricao(txtDescricao.getText());
        p.setValor(Double.parseDouble(txtValor.getText()));
        
        ProcedimentoDAO pDAO = new ProcedimentoDAO();
        
        pDAO.editar(p);
        limparformulario();
        
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        int idProcedimento = Integer.parseInt(txtID.getText());
        ProcedimentoDAO pDAO = new ProcedimentoDAO();
        
        Procedimento p = pDAO.getProcedimento(idProcedimento);
        if(p == null){
            txtID.setText("");
            txtProcedimento.setText("");
            txtDescricao.setText("");
            txtValor.setText("");
            JOptionPane.showMessageDialog(this, "Procedimento não encontrado!");
        } else{
            txtID.setText(String.valueOf(p.getId()));
            txtProcedimento.setText(p.getNome());
            txtDescricao.setText(p.getDescricao());
            txtValor.setText(String.valueOf(p.getValor()));
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        // TODO add your handling code here:
        int resposta = JOptionPane.showConfirmDialog(null, "Deseja realmente excluir ?",
                "Exclusão", JOptionPane.YES_NO_OPTION);
        if(resposta == JOptionPane.YES_OPTION){
            ProcedimentoDAO pDAO = new ProcedimentoDAO();
            pDAO.excluir(Integer.parseInt(txtID.getText()));
            limparformulario();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

